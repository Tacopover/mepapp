// B7-T09c-2a goal G6: a fan coil unit as the only equipment on a T-duct (no air handling unit), capacity 0 and then 80.
import { open } from '/root/MepApp/.claude/worktrees/buildings-b7/.claude/roadmap/browser/lib.mjs';
const SHOTS = '/root/MepApp/.claude/worktrees/buildings-b7/.claude/roadmap/work/shots/b7-t09c2a-journey/';
const t = await open({ width: 1600, height: 1000 });
const { page, check, idle } = t;
await t.start();
await t.openPdf();
const screenOf = (p) => page.evaluate((p) => { const s = window.__mepSketchScene; const g = s.world.toGlobal(p); const r = s.app.canvas.getBoundingClientRect(); return { x: r.left + g.x, y: r.top + g.y }; }, p);
const clickAt = async (p, wait = 300) => { const s = await screenOf(p); await page.mouse.click(s.x, s.y); await idle(wait); };
const snap = async (name) => { const path = `${SHOTS}fcu-${name}.png`; await page.screenshot({ path }); console.log(`SHOT ${path}`); };
await page.evaluate(() => { const s = window.__mepSketchScene; const r = s.app.canvas.getBoundingClientRect(); s.world.scale.set(1); s.world.x = 599 - r.left - 600; s.world.y = 480 - r.top - 670; });
await idle(300);
const Tm = { x: 900, y: 400 }, Tj = { x: 650, y: 400 }, O1 = { x: 400, y: 400 }, O2 = { x: 650, y: 600 };
await page.locator('button.mep-rail-btn[title="Stamp"]').first().click();
await idle(300);
await page.locator('.mep-dock input[placeholder^="Search"]').fill('Round Supply');
await idle(250);
await page.locator('.mep-stamp-tile').first().click();
await idle(1000);
await clickAt(Tm, 800);
await page.keyboard.press('Escape');
await page.locator('button.mep-rail-btn[title="Segment"]').first().click();
await idle(300);
await page.locator('.mep-dock button', { hasText: /^\s*Network Types\s*$/ }).first().click();
await idle(300);
await page.locator('.mep-dock').locator('text=Supply Air').first().click();
await idle(300);
await clickAt(Tm); await clickAt(Tj); await clickAt(O1); await page.keyboard.press('Escape'); await idle(200);
await clickAt(Tj); await clickAt(O2); await page.keyboard.press('Escape'); await idle(300);
const panel = () => page.evaluate(() => {
  const dock = document.querySelector('.mep-dock');
  const rows = [...dock.querySelectorAll('.mep-field-row')].map((r) => `${r.querySelector('label')?.textContent.trim()}=${r.querySelector('input,select')?.value ?? ''}`);
  const solved = [...dock.querySelectorAll('.mep-field-row')].find((r) => /^solved capacity/i.test(r.querySelector('label')?.textContent.trim() ?? ''))?.querySelector('input')?.value ?? null;
  return { solved, hints: [...dock.querySelectorAll('.mep-hint')].map((h) => h.textContent.trim().slice(0, 70)), rows };
});
const sel = async (p, label) => { await page.locator('button.mep-rail-btn[title="Select"]').first().click(); await idle(150); await clickAt(p, 400); const q = await panel(); console.log(`READ ${label}: ${q.solved} | hints ${JSON.stringify(q.hints)}`); return q; };
await sel({ x: Tm.x + 28, y: Tm.y + 24 }, 'terminal');
const cap = page.locator('.mep-dock .mep-field-row', { has: page.locator('label', { hasText: /^\s*Capacity/i }) }).locator('input').first();
await cap.click({ clickCount: 3 }); await page.keyboard.type('100'); await page.keyboard.press('Enter'); await idle(500);
// canvas numbers before and after the Solve flow button, T-duct with no source
const shotName = async (n) => { const path = `${SHOTS}overlay-${n}.png`; await page.screenshot({ path }); console.log(`SHOT ${path}`); };
await page.locator('button.mep-rail-btn[title="Select"]').first().click();
await idle(200);
await clickAt({ x: 1000, y: 560 }, 300);
await shotName('1-before-solve-flow-button');
const labels1 = await page.evaluate(() => window.__mepSketchScene.doc.flowLabelLayer.children.filter((c) => 'text' in c).map((c) => c.text));
console.log('CANVAS LABELS before button', JSON.stringify(labels1));
await page.locator('.mep-dock-tab-label', { hasText: /^Networks$/ }).click();
await idle(300);
await page.locator('button.mep-icon-btn', { hasText: /Solve flow/ }).click();
await idle(800);
const labels2 = await page.evaluate(() => window.__mepSketchScene.doc.flowLabelLayer.children.filter((c) => 'text' in c).map((c) => c.text));
console.log('CANVAS LABELS after button', JSON.stringify(labels2));
await shotName('2-after-solve-flow-button-networks-tab');
await page.locator('.mep-dock-tab-label', { hasText: /^Properties$/ }).click();
await idle(300);
await sel({ x: 525, y: 400 }, 's1 after the button');
await shotName('3-s1-panel-and-canvas');
check(labels2.length === 3, 'canvas shows three numbers after the Solve flow button', JSON.stringify(labels2));
check(labels2.every((x) => !/at most/.test(x)), 'canvas numbers have no "at most" while the panel says "at most 100" (finding if true)', JSON.stringify(labels2));
await t.finish();
